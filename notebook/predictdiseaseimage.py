# OPTIMIZATION 2: Improved Fusion Model with Attention Mechanism
class AttentionFusion(nn.Module):
    """Attention mechanism for feature fusion"""
    def __init__(self, num_features):
        super(AttentionFusion, self).__init__()
        self.attention = nn.Sequential(
            nn.Linear(num_features, num_features // 4),
            nn.ReLU(),
            nn.Linear(num_features // 4, num_features),
            nn.Sigmoid()
        )

    def forward(self, x):
        attention_weights = self.attention(x)
        return x * attention_weights

class ImprovedFusionModel(nn.Module):
    """
    Enhanced Fusion model with:
    - Fine-tuning of all layers
    - Attention mechanism
    - Batch Normalization
    - Improved classifier architecture
    """
    def __init__(self, num_classes):
        super(ImprovedFusionModel, self).__init__()

        # Load pre-trained models
        self.efficientnet_b0 = timm.create_model('efficientnet_b0', pretrained=True)
        self.efficientnet_b2 = timm.create_model('efficientnet_b2', pretrained=True)
        self.resnet50 = timm.create_model('resnet50', pretrained=True)

        # Get feature dimensions
        self.b0_features = self.efficientnet_b0.num_features
        self.b2_features = self.efficientnet_b2.num_features
        self.resnet_features = self.resnet50.num_features

        # Remove classification heads
        self.efficientnet_b0.classifier = nn.Identity()
        self.efficientnet_b2.classifier = nn.Identity()
        self.resnet50.fc = nn.Identity()

        # Total fused features
        self.total_features = self.b0_features + self.b2_features + self.resnet_features

        # OPTIMIZATION: Add attention mechanism
        self.attention = AttentionFusion(self.total_features)

        # OPTIMIZATION: Improved classifier with BatchNorm and residual connections
        self.bn1 = nn.BatchNorm1d(self.total_features)

        self.classifier = nn.Sequential(
            nn.Linear(self.total_features, 1024),
            nn.BatchNorm1d(1024),
            nn.ReLU(),
            nn.Dropout(0.5),

            nn.Linear(1024, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(),
            nn.Dropout(0.4),

            nn.Linear(512, 256),
            nn.BatchNorm1d(256),
            nn.ReLU(),
            nn.Dropout(0.3),

            nn.Linear(256, num_classes)
        )

    def forward(self, x):
        # Extract features from each model
        feat_b0 = self.efficientnet_b0(x)
        feat_b2 = self.efficientnet_b2(x)
        feat_resnet = self.resnet50(x)

        # Concatenate features (fusion)
        fused_features = torch.cat([feat_b0, feat_b2, feat_resnet], dim=1)

        # Apply batch normalization
        fused_features = self.bn1(fused_features)

        # Apply attention mechanism
        fused_features = self.attention(fused_features)

        # Classification
        output = self.classifier(fused_features)

        return output

