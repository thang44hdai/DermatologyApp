# OPTIMIZATION 3: Label Smoothing for better generalization
class LabelSmoothingCrossEntropy(nn.Module):
    def __init__(self, epsilon=0.1, weight=None):
        super(LabelSmoothingCrossEntropy, self).__init__()
        self.epsilon = epsilon
        self.weight = weight

    def forward(self, outputs, targets):
        n_classes = outputs.size(-1)
        log_probs = torch.nn.functional.log_softmax(outputs, dim=-1)

        # One-hot encoding with label smoothing
        targets_one_hot = torch.zeros_like(log_probs).scatter_(1, targets.unsqueeze(1), 1)
        targets_smooth = targets_one_hot * (1 - self.epsilon) + self.epsilon / n_classes

        loss = -(targets_smooth * log_probs).sum(dim=-1)

        if self.weight is not None:
            loss = loss * self.weight[targets]

        return loss.mean()

